print("7 // 2 =", 7 // 2)
print("-7 // 2 =", -7 // 2)
print("7 // -2 =", 7 // -2)
print("-7 // -2 =", -7 // -2)

print("\nExplanation:")
print("Floor division rounds down toward negative infinity.")
print("Therefore, -3.5 becomes -4, not -3.")
print("Simply removing the decimal part would round it toward zero.")
